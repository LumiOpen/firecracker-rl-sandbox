def all_phrases() -> tuple[str, ...]:
    """Unique phrases, longest first, so a shorter wording does not hide a longer one."""
    seen: dict[str, str] = {}
    for phrases in MARKERS.values():
        for phrase in phrases:
            folded = phrase.casefold()
            if folded and folded not in seen:
                seen[folded] = phrase
    return tuple(sorted(seen.values(), key=lambda phrase: len(phrase.casefold()), reverse=True))
